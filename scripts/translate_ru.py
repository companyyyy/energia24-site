def translate_value_ru(value):
    # "так"/"ні" замінюємо лише як окремі значення, щоб не зачепити інші слова.
    if value in ("так", "ні"):
        return {"так": "да", "ні": "нет"}[value]
    if value.startswith("так, "):
        value = "да, " + value[len("так, "):]
    for ua, ru in VALUES_RU:
        value = value.replace(ua, ru)
    return value
