def _ivem(power, bat_v, ac_charge, ac_charge_adj, pv_range, pv_power, pv_current, start_v,
          parallel, weight, size):
    return (
        [("Номінальна потужність", f"{power} Вт ({power} ВА)"),
         ("Номінальна напруга АКБ", f"{bat_v} В")]
        + _IVEM_AC
        + [("Макс. струм заряджання від мережі/генератора", f"{ac_charge} А (регулювання {ac_charge_adj}, крок 1 А)"),
           ("Макс. напруга холостого ходу PV", "500 В"),
           ("Робочий діапазон напруги PV", pv_range),
           ("Макс. потужність PV", pv_power),
           ("Макс. струм сонячного заряджання", f"{ac_charge} А"),
           ("Макс. сумарний струм заряджання (PV + мережа)", f"{ac_charge} А"),
           ("Макс. вхідний струм PV", pv_current),
           ("Мін. стартова напруга PV", start_v)]
        + _IVEM_OUT
        + [("Паралельна робота", parallel)]
        + _IVEM_TAIL
        + [("Розміри", size), ("Вага", weight)]
    )


